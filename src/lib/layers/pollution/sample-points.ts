function gridName(lat: number, lon: number): string {
  const ns = lat >= 0 ? "N" : "S";
  const ew = lon >= 0 ? "E" : "O";
  return `Rejilla ${Math.abs(lat)}°${ns} ${Math.abs(lon)}°${ew}`;
}

function buildGrid(cities: readonly SamplePoint[]): SamplePoint[] {
  const grid: SamplePoint[] = [];
  for (let lat = -60; lat <= 75; lat += 15) {
    for (let lon = -180; lon <= 160; lon += 20) {
      const nearCity = cities.some((c) => Math.abs(c.lat - lat) < 3 && Math.abs(c.lon - lon) < 3);
      if (nearCity) continue;
      grid.push({ id: `grid-${lat}-${lon}`, name: gridName(lat, lon), country: "", lat, lon, kind: "grid" });
    }
  }
  return grid;
}

/** Cities (population order) followed by the grid points that are not already covered by a city. */
export const SAMPLE_POINTS: readonly SamplePoint[] = [...CITIES, ...buildGrid(CITIES)];
