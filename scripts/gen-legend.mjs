// Generates src/lib/layers/ozone/legend-ozone.ts from the GIBS OMI TOMS colormap XML.
// Usage: node scripts/gen-legend.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = new URL("../", import.meta.url);
const xml = readFileSync(new URL("public/sites/orbitalwatch/data/colormap-OMI_Ozone_TOMS_Total_Column.xml", root), "utf8");

const MIN = 100;
const MAX = 500;
const STOPS = 12;

const entries = [];
for (const tag of xml.match(/<ColorMapEntry\b[^>]*\/?>/g) ?? []) {
  if (/transparent="true"/.test(tag) || /nodata="true"/.test(tag)) continue;
  const rgb = /rgb="(\d+),(\d+),(\d+)"/.exec(tag);
  const range = /sourceValue="[[(]([^,]+),([^)\]]+)[)\]]"/.exec(tag);
  if (!rgb || !range) continue;
  const lo = range[1] === "-INF" ? -Infinity : Number(range[1]);
  const hi = /INF/.test(range[2]) ? Infinity : Number(range[2]);
  entries.push({ lo, hi, rgb: [Number(rgb[1]), Number(rgb[2]), Number(rgb[3])] });
}
if (entries.length === 0) throw new Error("No ColorMapEntry parsed");

const hex = (rgb) => "#" + rgb.map((c) => c.toString(16).padStart(2, "0")).join("");
const stops = [];
for (let i = 0; i < STOPS; i++) {
  const at = i / (STOPS - 1);
  const du = MIN + at * (MAX - MIN);
  const entry = entries.find((e) => du >= e.lo && du < e.hi) ?? entries[entries.length - 1];
  stops.push({ at: Number(at.toFixed(4)), color: hex(entry.rgb) });
}

const stopLines = stops.map((s) => `    { at: ${s.at}, color: "${s.color}" },`).join("\n");
const out = `// generated by scripts/gen-legend.mjs — do not edit
import type { LegendSpec } from "@/types/layers";

/** Total column below which the ozone layer is considered a hole (DU). */
export const OZONE_HOLE_DU = 220;

/** Colour scale range in Dobson units. */
export const OZONE_RANGE_DU = [100, 500] as const;

/** Legend of the OMI total ozone column (12 stops sampled from the GIBS colormap). */
export const OZONE_LEGEND: LegendSpec = {
  title: "Ozono total",
  unit: "DU",
  stops: [
${stopLines}
  ],
  ticks: [100, 220, 300, 400, 500].map((v) => ({ at: (v - 100) / 400, label: String(v) })),
  notes: ["220 DU: umbral de agujero de ozono"],
};
`;
writeFileSync(fileURLToPath(new URL("src/lib/layers/ozone/legend-ozone.ts", root)), out);
console.log(`wrote ${STOPS} stops from ${entries.length} entries`);
